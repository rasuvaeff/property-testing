import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDir = dirname(fileURLToPath(import.meta.url))
const docsDir = join(scriptsDir, '..')

const REPO_BLOB = 'https://github.com/rasuvaeff/property-testing/blob/master/'
const NAMESPACE_PREFIX = 'Rasuvaeff\\PropertyTesting\\'

// English is the unprefixed root locale; Russian keeps its 'ru/' subdirectory.
function outDir(lang) {
    return lang === 'en' ? join(docsDir, 'api', 'classes') : join(docsDir, lang, 'api', 'classes')
}

function sourcePath(className) {
    return className.slice(NAMESPACE_PREFIX.length).replaceAll('\\', '/') + '.php'
}

function shortName(className) {
    const parts = className.split('\\')
    return parts[parts.length - 1]
}

function shortenType(type) {
    if (type === undefined || type === null) {
        return 'mixed'
    }
    return type.replaceAll(NAMESPACE_PREFIX, '')
}

function formatParams(params) {
    return params.map((p) => `${shortenType(p.type)} $${p.name}`).join(', ')
}

function methodSignature(method) {
    const prefix = method.static ? 'static ' : ''
    const returns = shortenType(method.returnType)
    return `${prefix}${method.name}(${formatParams(method.params)}): ${returns}`
}

// A fenced ```php block (real syntax highlighting) reads far better than an
// inline-code heading, especially once a signature has enough params to wrap
// mid-identifier — one param per line + trailing comma for a long list,
// matching this codebase's own style.
function methodSignatureBlock(method) {
    const oneLine = methodSignature(method)
    if (method.params.length <= 2 && oneLine.length <= 88) {
        return oneLine
    }

    const prefix = method.static ? 'static ' : ''
    const returns = shortenType(method.returnType)
    const params = method.params.map((p) => `    ${shortenType(p.type)} $${p.name},`).join('\n')

    return `${prefix}${method.name}(\n${params}\n): ${returns}`
}

function firstSentence(text, maxLen) {
    const flat = text.replace(/\s+/g, ' ').trim()
    if (flat === '') return ''
    const boundary = flat.slice(0, maxLen + 1).search(/[.!?](\s|$)/)
    if (boundary !== -1 && boundary <= maxLen) return flat.slice(0, boundary + 1)
    if (flat.length <= maxLen) return flat
    const truncated = flat.slice(0, maxLen - 1)
    const lastSpace = truncated.lastIndexOf(' ')
    return (lastSpace > 0 ? truncated.slice(0, lastSpace) : truncated).trimEnd() + '…'
}

function renderProse(text) {
    return text
        .split('\n\n')
        .map((p) => p.trim())
        .filter(Boolean)
        .join('\n\n')
}

function renderClass(entry, lang) {
    const name = shortName(entry.class)
    const src = REPO_BLOB + 'src/' + sourcePath(entry.class)
    const kindLabel = { en: { class: 'Class', interface: 'Interface', enum: 'Enum' }, ru: { class: 'Класс', interface: 'Интерфейс', enum: 'Enum' } }[lang][entry.kind]
    const kindLower = { class: 'class', interface: 'interface', enum: 'enum' }[entry.kind]
    const heading = lang === 'en' ? 'Properties' : 'Свойства'
    const methodsHeading = lang === 'en' ? 'Methods' : 'Методы'
    const noPublicApi = lang === 'en' ? 'No public properties or methods beyond the constructor.' : 'Нет публичных свойств или методов кроме конструктора.'
    const propCols = lang === 'en' ? ['Property', 'Type', 'Readonly'] : ['Свойство', 'Тип', 'Readonly']
    const sourceLabel = lang === 'en' ? 'Source' : 'Исходник'
    const extendsLabel = lang === 'en' ? 'Extends' : 'Наследует'
    const banner =
        lang === 'en'
            ? `<!-- AUTO-GENERATED by docs/scripts/generate-api.mjs from a reflection pass over src/ (docs/scripts/reflect-api.php) — do not edit this file directly. -->`
            : `<!-- АВТОГЕНЕРАЦИЯ: docs/scripts/generate-api.mjs, проход рефлексии по src/ (docs/scripts/reflect-api.php) — не редактировать вручную. -->`
    const fallbackDescription =
        lang === 'en'
            ? `${name} — ${kindLower} in the property-testing API reference.`
            : `${name} — ${kindLower} в справочнике API property-testing.`
    const description = entry.summary ? firstSentence(entry.summary, 155) : fallbackDescription
    // PHPDoc prose is written once, in English, in the source — translating it
    // per-release for every class/method isn't sustainable and would drift
    // from the code immediately. Show it as-is on the RU pages too (a short
    // disclaimer instead of silently mixing languages) rather than omitting
    // it and leaving RU readers with bare signatures only.
    const englishProseNote = 'Текст ниже — на английском, из PHPDoc в исходном коде.'

    const lines = []
    lines.push('---')
    lines.push(`title: "${name}"`)
    lines.push(`description: ${JSON.stringify(description)}`)
    lines.push('---')
    lines.push('')
    lines.push(banner)
    lines.push('')
    lines.push(`# \`${name}\``)
    lines.push('')
    lines.push(`\`${entry.class}\``)
    lines.push('')
    lines.push(`**${kindLabel}** — [${sourceLabel}](${src})${entry.extends ? ` — **${extendsLabel}:** \`${shortenType(entry.extends)}\`` : ''}`)
    lines.push('')

    if (entry.summary) {
        if (lang === 'ru') {
            lines.push(`*${englishProseNote}*`)
            lines.push('')
        }
        lines.push(renderProse(entry.summary))
        lines.push('')
    }

    if (entry.publicProperties.length > 0) {
        lines.push(`## ${heading}`)
        lines.push('')
        lines.push(`| ${propCols.join(' | ')} |`)
        lines.push('|---|---|---|')
        for (const prop of entry.publicProperties) {
            lines.push(`| \`${prop.name}\` | \`${shortenType(prop.type)}\` | ${prop.readonly ? 'yes' : 'no'} |`)
        }
        lines.push('')
    }

    if (entry.publicMethods.length > 0) {
        lines.push(`## ${methodsHeading}`)
        lines.push('')
        for (const method of entry.publicMethods) {
            lines.push(`### ${method.name}()`)
            lines.push('')
            lines.push('```php')
            lines.push(methodSignatureBlock(method))
            lines.push('```')
            lines.push('')
            if (method.summary) {
                lines.push(renderProse(method.summary))
                lines.push('')
            }
            const documentedParams = method.params.filter((p) => p.description !== '')
            if (documentedParams.length > 0) {
                for (const p of documentedParams) {
                    lines.push(`- \`$${p.name}\` — ${p.description}`)
                }
                lines.push('')
            }
        }
    }

    if (entry.publicProperties.length === 0 && entry.publicMethods.length === 0) {
        lines.push(noPublicApi)
        lines.push('')
    }

    return lines.join('\n')
}

function clean(dir) {
    try {
        for (const entry of readdirSync(dir)) {
            rmSync(join(dir, entry), { recursive: true, force: true })
        }
    } catch {
        // directory does not exist yet
    }
}

const snapshot = JSON.parse(readFileSync(join(scriptsDir, 'api-snapshot.json'), 'utf8'))
const apiEntries = snapshot.filter((entry) => entry.isApi)

for (const lang of ['en', 'ru']) {
    const dir = outDir(lang)
    mkdirSync(dir, { recursive: true })
    clean(dir)
    for (const entry of apiEntries) {
        const outPath = join(dir, `${shortName(entry.class)}.md`)
        writeFileSync(outPath, renderClass(entry, lang) + '\n', 'utf8')
    }
}

console.log(`Generated ${apiEntries.length} API class pages into docs/api/classes/** (en, root) and docs/ru/api/classes/**.`)

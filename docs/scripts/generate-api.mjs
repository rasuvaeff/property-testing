import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDir = dirname(fileURLToPath(import.meta.url))
const docsDir = join(scriptsDir, '..')

const REPO_BLOB = 'https://github.com/rasuvaeff/property-testing/blob/master/'
const NAMESPACE_PREFIX = 'Rasuvaeff\\PropertyTesting\\'

function sourcePath(className) {
    return className.slice(NAMESPACE_PREFIX.length).replaceAll('\\', '/') + '.php'
}

function shortName(className) {
    const parts = className.split('\\')
    return parts[parts.length - 1]
}

function shortenType(type) {
    if (type === undefined || type === null) {
        return 'mixed'
    }
    return type.replaceAll(NAMESPACE_PREFIX, '')
}

function formatParams(params) {
    return params.map((p) => `${shortenType(p.type)} $${p.name}`).join(', ')
}

function methodSignature(method) {
    const prefix = method.static ? 'static ' : ''
    const returns = shortenType(method.returnType)
    return `${prefix}${method.name}(${formatParams(method.params)}): ${returns}`
}

function renderClass(entry, lang) {
    const name = shortName(entry.class)
    const src = REPO_BLOB + 'src/' + sourcePath(entry.class)
    const kindLabel = { en: { class: 'Class', interface: 'Interface', enum: 'Enum' }, ru: { class: 'Класс', interface: 'Интерфейс', enum: 'Enum' } }[lang][entry.kind]
    const heading = lang === 'en' ? 'Properties' : 'Свойства'
    const methodsHeading = lang === 'en' ? 'Methods' : 'Методы'
    const noPublicApi = lang === 'en' ? 'No public properties or methods beyond the constructor.' : 'Нет публичных свойств или методов кроме конструктора.'
    const propCols = lang === 'en' ? ['Property', 'Type', 'Readonly'] : ['Свойство', 'Тип', 'Readonly']
    const methodCols = lang === 'en' ? ['Method'] : ['Метод']
    const sourceLabel = lang === 'en' ? 'Source' : 'Исходник'
    const extendsLabel = lang === 'en' ? 'Extends' : 'Наследует'
    const banner =
        lang === 'en'
            ? `<!-- AUTO-GENERATED by docs/scripts/generate-api.mjs from a reflection pass over src/ (docs/scripts/reflect-api.php) — do not edit this file directly. -->`
            : `<!-- АВТОГЕНЕРАЦИЯ: docs/scripts/generate-api.mjs, проход рефлексии по src/ (docs/scripts/reflect-api.php) — не редактировать вручную. -->`

    const lines = []
    lines.push('---')
    lines.push(`title: "${name}"`)
    lines.push('---')
    lines.push('')
    lines.push(banner)
    lines.push('')
    lines.push(`# \`${name}\``)
    lines.push('')
    lines.push(`\`${entry.class}\``)
    lines.push('')
    lines.push(`**${kindLabel}** — [${sourceLabel}](${src})${entry.extends ? ` — **${extendsLabel}:** \`${shortenType(entry.extends)}\`` : ''}`)
    lines.push('')

    if (entry.publicProperties.length > 0) {
        lines.push(`## ${heading}`)
        lines.push('')
        lines.push(`| ${propCols.join(' | ')} |`)
        lines.push('|---|---|---|')
        for (const prop of entry.publicProperties) {
            lines.push(`| \`${prop.name}\` | \`${shortenType(prop.type)}\` | ${prop.readonly ? 'yes' : 'no'} |`)
        }
        lines.push('')
    }

    if (entry.publicMethods.length > 0) {
        lines.push(`## ${methodsHeading}`)
        lines.push('')
        lines.push(`| ${methodCols.join(' | ')} |`)
        lines.push('|---|')
        for (const method of entry.publicMethods) {
            lines.push(`| \`${methodSignature(method)}\` |`)
        }
        lines.push('')
    }

    if (entry.publicProperties.length === 0 && entry.publicMethods.length === 0) {
        lines.push(noPublicApi)
        lines.push('')
    }

    return lines.join('\n')
}

function clean(dir) {
    try {
        for (const entry of readdirSync(dir)) {
            rmSync(join(dir, entry), { recursive: true, force: true })
        }
    } catch {
        // directory does not exist yet
    }
}

const snapshot = JSON.parse(readFileSync(join(scriptsDir, 'api-snapshot.json'), 'utf8'))
const apiEntries = snapshot.filter((entry) => entry.isApi)

for (const lang of ['en', 'ru']) {
    const outDir = join(docsDir, lang, 'api', 'classes')
    mkdirSync(outDir, { recursive: true })
    clean(outDir)
    for (const entry of apiEntries) {
        const outPath = join(outDir, `${shortName(entry.class)}.md`)
        writeFileSync(outPath, renderClass(entry, lang) + '\n', 'utf8')
    }
}

console.log(`Generated ${apiEntries.length} API class pages into docs/en/api/classes/** and docs/ru/api/classes/**.`)

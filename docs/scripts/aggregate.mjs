import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDir = dirname(fileURLToPath(import.meta.url))
const docsDir = join(scriptsDir, '..')
const pkgDir = join(docsDir, '..')

const sectionMap = JSON.parse(readFileSync(join(scriptsDir, 'section-map.json'), 'utf8'))

const REPO_BLOB = 'https://github.com/rasuvaeff/property-testing/blob/master/'

function rewriteRelativeLinks(markdown) {
    return markdown.replace(/\]\((?!https?:|#|\/)([^)]+)\)/g, (_match, target) => `](${REPO_BLOB}${target})`)
}

function splitHeadings(markdown) {
    const lines = markdown.split('\n')
    const headings = []
    lines.forEach((line, index) => {
        const match = /^(#{2,3})\s+(.*)$/.exec(line)
        if (match) {
            headings.push({ level: match[1].length, text: match[2].trim(), line: index })
        }
    })
    return { lines, headings }
}

function extractSections(markdown) {
    const { lines, headings } = splitHeadings(markdown)
    if (headings.length !== sectionMap.length) {
        throw new Error(
            `Heading count mismatch: source has ${headings.length} headings (## or ###), ` +
                `section-map.json has ${sectionMap.length} entries. A README heading was added, removed, ` +
                `or renumbered without updating scripts/section-map.json — the aggregator refuses to guess.`,
        )
    }
    return headings.map((heading, index) => {
        const end = index + 1 < headings.length ? headings[index + 1].line : lines.length
        return { entry: sectionMap[index], text: lines.slice(heading.line, end).join('\n').trimEnd() }
    })
}

function normalizeHeading(heading) {
    return heading.replace(/[`*]/g, '').trim().toLowerCase()
}

function stripHeadingMarker(sectionText) {
    // Section headings become H2 inside the page regardless of their level in the
    // README (### under a page's own H1 still reads as a subsection, not H4).
    return sectionText.replace(/^#{2,3}\s+/, '## ')
}

function dropRedundantHeading(sectionText) {
    // The page's own H1 (from entry.title) already says this; don't repeat it as H2.
    return sectionText.replace(/^#{2,3}\s+.*\n/, '')
}

function aggregate(lang, readmePath) {
    const readme = readFileSync(join(pkgDir, readmePath), 'utf8')
    const sections = extractSections(readme)

    const openedFiles = new Map()

    for (const { entry, text } of sections) {
        if (!entry.file) continue

        const outPath = join(docsDir, lang, entry.file)
        const isFirstForFile = !openedFiles.has(entry.file)

        if (isFirstForFile) {
            mkdirSync(dirname(outPath), { recursive: true })
            const title = entry.title ? entry.title[lang] : entry.file
            const banner =
                `---\ntitle: ${JSON.stringify(title)}\n---\n\n` +
                `<!-- AUTO-GENERATED by docs/scripts/aggregate.mjs from ${readmePath} — do not edit this file directly. -->\n\n` +
                `# ${title}\n\n`
            openedFiles.set(entry.file, title)
            writeFileSync(outPath, banner, 'utf8')
        }

        const sectionHeadingMatch = /^#{2,3}\s+(.*)/.exec(text.split('\n', 1)[0])
        const title = openedFiles.get(entry.file)
        const redundant =
            isFirstForFile && sectionHeadingMatch && normalizeHeading(sectionHeadingMatch[1]) === normalizeHeading(title)

        const body = rewriteRelativeLinks(redundant ? dropRedundantHeading(text) : stripHeadingMarker(text))
        writeFileSync(outPath, body.trimStart() + '\n\n', { flag: 'a' })
    }
}

aggregate('en', 'README.md')
aggregate('ru', 'README.ru.md')

// ROADMAP.md, UPGRADE.md and llms.txt have no README.ru.md-style RU sibling —
// they're single English source files. Import them whole (not split by
// heading) into en/, and give ru/ a short pointer page instead of a fake
// machine translation of release-engineering prose.
const directImports = [
    { source: 'ROADMAP.md', file: 'roadmap.md', title: { en: 'Roadmap', ru: 'Roadmap' } },
    { source: 'UPGRADE.md', file: 'migrating-from-1x.md', title: { en: 'Migrating from 1.x', ru: 'Миграция с 1.x' } },
    { source: 'llms.txt', file: 'llms.md', title: { en: 'llms.txt reference', ru: 'Справочник llms.txt' } },
]

function importWhole(entry) {
    const raw = readFileSync(join(pkgDir, entry.source), 'utf8')
    const body = rewriteRelativeLinks(raw)
    const enTitle = entry.title.en
    const enPath = join(docsDir, 'en', entry.file)
    mkdirSync(dirname(enPath), { recursive: true })
    writeFileSync(
        enPath,
        `---\ntitle: ${JSON.stringify(enTitle)}\n---\n\n` +
            `<!-- AUTO-GENERATED by docs/scripts/aggregate.mjs from ${entry.source} — do not edit this file directly. -->\n\n` +
            body.trimStart() +
            '\n',
        'utf8',
    )

    const ruTitle = entry.title.ru
    const ruPath = join(docsDir, 'ru', entry.file)
    mkdirSync(dirname(ruPath), { recursive: true })
    writeFileSync(
        ruPath,
        `---\ntitle: ${JSON.stringify(ruTitle)}\n---\n\n` +
            `# ${ruTitle}\n\n` +
            `Этот документ — единый источник (\`${entry.source}\`), без отдельной RU-версии ` +
            `(в отличие от README, у него нет \`.ru\`-зеркала). Смотрите английский оригинал: ` +
            `[${enTitle}](/en/${entry.file.replace(/\.md$/, '')}).\n`,
        'utf8',
    )
}

for (const entry of directImports) {
    importWhole(entry)
}

console.log(
    `Aggregated ${sectionMap.filter((entry) => entry.file).length} sections into docs/en/** and docs/ru/**, ` +
        `plus ${directImports.length} direct imports (en full + ru pointer).`,
)
